"""Compilador determinista de adaptadores multi-herramienta para Datalaria Helix (INV-HELIX-4).

Lee las 12 fichas canónicas desde `specs/squad/*.md` y genera:
1. `.agents/squad/<id>.md` + `.agents/squad/manifest.json` (Google Antigravity)
2. `.claude/agents/<id>.md` (Anthropic Claude Code Subagents)
3. `.cursor/rules/helix-squad.mdc` (Cursor IDE Rules)

Uso:
    python -m ops.helix.build_adapters
    python -m ops.helix.build_adapters --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from ops.helix.models import AgentSpecDocument, load_squad_specs

AUTO_HEADER_COMMENT = (
    "<!-- AUTO-GENERATED BY ops/helix/build_adapters.py — DO NOT EDIT MANUALLY (INV-HELIX-4) -->\n"
    "<!-- Source of Truth: {source_path} -->\n"
)


def render_antigravity_adapter(doc: AgentSpecDocument) -> str:
    """Genera la ficha optimizada para Google Antigravity en .agents/squad/<id>.md."""
    fm = doc.frontmatter
    header = AUTO_HEADER_COMMENT.format(source_path=doc.source_path)
    meta_summary = (
        f"> **ID:** `{fm.id}` · **Célula:** `{fm.cell}` · "
        f"**Tallas:** `{', '.join(fm.activates_on_sizes)}` · "
        f"**Código Prod:** `{fm.can_write_production_code}` · "
        f"**Veto:** `{fm.has_veto_power}`\n\n"
    )
    return f"{header}\n{meta_summary}{doc.body_markdown}\n"


def render_claude_subagent(doc: AgentSpecDocument) -> str:
    """Genera un subagente nativo para Claude Code en .claude/agents/<id>.md."""
    fm = doc.frontmatter
    tools = (
        "Read, Grep, Glob, Bash, Edit, Write"
        if fm.can_write_production_code
        else "Read, Grep, Glob, Bash"
    )
    description = (
        f"{fm.icon} {fm.name_es} ({fm.name_en}) — Célula '{fm.cell}'. "
        f"Se activa en tallas [{', '.join(fm.activates_on_sizes)}] y triggers [{', '.join(fm.mandatory_triggers)}]. "
        f"Veto={fm.has_veto_power}."
    )
    frontmatter_claude = (
        "---\n"
        f"name: {fm.id}\n"
        f"description: \"{description}\"\n"
        f"tools: {tools}\n"
        "---\n\n"
    )
    header = AUTO_HEADER_COMMENT.format(source_path=doc.source_path)
    return f"{frontmatter_claude}{header}\n{doc.body_markdown}\n"


def render_cursor_mdc(docs: list[AgentSpecDocument]) -> str:
    """Genera la regla .cursor/rules/helix-squad.mdc con el índice y rúbrica bajo demanda."""
    rows = []
    for d in docs:
        fm = d.frontmatter
        veto_badge = "SÍ (VETO)" if fm.has_veto_power else "No"
        prod_badge = "Sí" if fm.can_write_production_code else "No"
        rows.append(
            f"| `{fm.id}` | {fm.icon} **{fm.name_es}** | `{fm.cell}` | `{', '.join(fm.activates_on_sizes)}` | {prod_badge} | {veto_badge} | `{d.source_path}` |"
        )
    table_md = "\n".join(rows)
    return (
        "---\n"
        "description: \"Datalaria Helix 12-Agent SDD Squad — On-Demand Triage & Verification Protocol (INV-HELIX-1..7)\"\n"
        "globs: \"**/*\"\n"
        "alwaysApply: true\n"
        "---\n\n"
        "<!-- AUTO-GENERATED BY ops/helix/build_adapters.py — DO NOT EDIT MANUALLY (INV-HELIX-4) -->\n\n"
        "# Datalaria Helix — Regla de Orquestación de 12 Agentes bajo SDD\n\n"
        "1. **Arranque en 3 pasos:** Lee `specs/ROADMAP.md`, `specs/_constitution.md` (`v1.1.0`) y la `spec.md` activa.\n"
        "2. **Triaje Bajo Demanda (`INV-HELIX-2`):** Clasifica la tarea (`XS`, `S`, `M`, `L`, `XL`) según `specs/squad/triage-rubric.md`, emite el bloque `TRIAGE HELIX` de 6 líneas y lee **únicamente** las fichas de los agentes convocados.\n"
        "3. **Separación Construcción/Verificación (`INV-HELIX-1`):** Ningún constructor (`04` a `09`) aprueba su propio trabajo. `10-security-privacy` y `11-qa-verifier` tienen derecho a veto vinculante.\n\n"
        "| ID | Rol | Célula | Tallas | ¿Código Prod? | ¿Veto? | Ficha Canónica |\n"
        "| :--- | :--- | :--- | :--- | :-: | :-: | :--- |\n"
        f"{table_md}\n"
    )


def render_manifest_json(docs: list[AgentSpecDocument]) -> str:
    """Genera el manifiesto JSON estructurado en .agents/squad/manifest.json."""
    payload = {
        "schema_version": "1.0.0",
        "generator": "ops/helix/build_adapters.py",
        "invariants": [f"INV-HELIX-{i}" for i in range(1, 9)],
        "total_agents": len(docs),
        "agents": [
            {
                **d.frontmatter.model_dump(),
                "source_path": d.source_path,
                "antigravity_adapter": f".agents/squad/{d.frontmatter.id}.md",
                "claude_adapter": f".claude/agents/{d.frontmatter.id}.md",
            }
            for d in docs
        ],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def build_adapters(root_dir: Path | str = Path("."), check_only: bool = False) -> dict[str, str]:
    """Compila (o verifica en modo --check) todos los adaptadores desde specs/squad/."""
    root = Path(root_dir)
    docs = load_squad_specs(root / "specs" / "squad")

    expected_files: dict[Path, str] = {}
    for doc in docs:
        agent_id = doc.frontmatter.id
        expected_files[root / ".agents" / "squad" / f"{agent_id}.md"] = render_antigravity_adapter(doc)
        expected_files[root / ".claude" / "agents" / f"{agent_id}.md"] = render_claude_subagent(doc)

    expected_files[root / ".agents" / "squad" / "manifest.json"] = render_manifest_json(docs)
    expected_files[root / ".cursor" / "rules" / "helix-squad.mdc"] = render_cursor_mdc(docs)

    drifted: list[str] = []
    for path, content in expected_files.items():
        if check_only:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                drifted.append(path.as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if check_only and drifted:
        raise RuntimeError(
            f"Detectada desincronización de adaptadores (INV-HELIX-4) en: {drifted}. "
            "Ejecuta 'python -m ops.helix.build_adapters'."
        )

    return {p.relative_to(root).as_posix(): c for p, c in expected_files.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description="Compilador de adaptadores Datalaria Helix (INV-HELIX-4).")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verifica que los adaptadores compilados coinciden al 100% con specs/squad/ sin escribir en disco.",
    )
    args = parser.parse_args()
    try:
        generated = build_adapters(Path("."), check_only=args.check)
        mode_label = "VERIFICADOS (--check)" if args.check else "COMPILADOS"
        print(f"[HELIX ADAPTERS] {len(generated)} artefactos {mode_label} exitosamente desde specs/squad/*.md.")
        return 0
    except Exception as exc:
        print(f"[HELIX ADAPTERS ERROR] {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
