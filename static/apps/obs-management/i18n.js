export function formatEur(amount, lang = 'es') {
const locale = lang === 'en' ? 'en-IE' : 'es-ES';
return new Intl.NumberFormat(locale, {
style: 'currency',
currency: 'EUR',
minimumFractionDigits: 2,
maximumFractionDigits: 2,
}).format(Number.isFinite(amount) ? amount : 0);
}
export function formatInt(num, lang = 'es') {
const locale = lang === 'en' ? 'en-US' : 'es-ES';
return new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(Math.round(num || 0));
}
export function interpolate(template, vars = {}) {
return String(template || '').replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
